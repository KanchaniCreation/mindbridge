package com.mindbridge.journal;

import java.util.List;

/** Neutral, non-judgmental starting points. They are suggestions, never instructions. */
public final class JournalPrompts {

    public static final List<String> ALL = List.of(
        "What is on your mind right now?",
        "What happened today that you would like to remember?",
        "What is one thing that felt difficult today, and what made it so?",
        "What is one small thing that went okay today?",
        "How has your energy been lately?",
        "Is there something you have been putting off? What makes it hard to start?",
        "What would you like to tell a friend who was in your situation?",
        "What is one small step you could take tomorrow?",
        "What are you looking forward to, even a little?",
        "Who or what helped you recently?"
    );

    private JournalPrompts() {
    }
}
